import type { DropDef } from './spawns';
import { TILE } from '../world/terrain';

export type AnimalSize = 'small' | 'large';

export interface AnimalDef {
  id: string;
  name: string;
  level: number;
  size: AnimalSize;
  hp: number;
  /** damage per bite when retaliating */
  damage: number;
  defense: number;
  /** percentage damage reduction */
  armor: number;
  attackCooldownSec: number;
  wanderSpeed: number;
  chaseSpeed: number;
  /** distance at which a retaliating animal gives up */
  leashRange: number;
  /** seconds out of leash before it goes back to wandering */
  disengageSec: number;
  drops: DropDef[];
  /** tile ids this species spawns on */
  habitat: number[];
  /** lives in water instead of land */
  aquatic?: boolean;
  /** swims away when hit instead of fighting back */
  flees?: boolean;
  /** large predators charge the player without being hit first */
  aggressive?: boolean;
  /** how close the player must be before an aggressive animal charges */
  aggroRange?: number;
}

